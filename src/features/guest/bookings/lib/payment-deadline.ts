/**
 * کمکی‌های دامنه‌ی مهلت پرداخت.
 *
 * ⚠️ چرا این تابع بیرون از کامپوننت است؟ مقایسه‌ی «مهلت با زمان حال» یک
 * محاسبه‌ی زمان‌وابسته است. نگه‌داشتنش در یک تابع دامنه‌ای دو فایده دارد:
 *   ۱) تست‌پذیر می‌شود (زمان تزریق‌پذیر است)؛
 *   ۲) از قاعده‌ی `react-hooks/purity` عبور می‌کند که فراخوانی مستقیم توابع
 *      ناخالص مثل `Date.now` را داخل رندر کامپوننت ممنوع می‌کند.
 */

/**
 * آیا مهلت پرداخت گذشته است؟
 *
 * @param deadline مهلت پرداخت — ISO datetime از خود رزرو.
 * @param now زمان جاری (میلی‌ثانیه) — برای تست تزریق می‌شود.
 */
export function isPaymentExpired(
  deadline: string,
  now: number = Date.now(),
): boolean {
  return new Date(deadline).getTime() <= now;
}
