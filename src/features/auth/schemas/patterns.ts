/**
 * الگوهای regex اعتبارسنجی احراز هویت.
 *
 * همه‌ی الگوها اینجا متمرکزند تا تعریف دوباره و ناهماهنگ‌شدن رخ ندهد.
 */

/**
 * نام: فقط حروف (فارسی/لاتین)، فاصله، نقطه، خط تیره و نیم‌فاصله‌ی ZWNJ.
 *
 * عمداً اعداد و کاراکترهای ویژه اجازه ندارند — نام واقعی به آن‌ها نیاز
 * ندارد و اجازه‌دادن، راه را برای ورودی زباله باز می‌کند.
 */
export const NAME_PATTERN = /^[\p{L}\u200c .'-]+$/u;

/**
 * ایمیل: عمداً فقط ASCII.
 *
 * کاراکترهای غیرلاتین در ایمیل کاربر را سردرگم می‌کند و اکثر سرویس‌دهنده‌ها
 * هم نمی‌پذیرند؛ پس همان استاندارد عملی را اعمال می‌کنیم.
 */
export const EMAIL_PATTERN = /^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$/;

/** کاراکترهای چاپ‌شدنی ASCII — برای رد کردن ارقام فارسی در ایمیل. */
export const ASCII_PRINTABLE_PATTERN = /^[\x20-\x7E]+$/;

/** فقط رقم لاتین — بعد از `normalizeDigits`. */
export const DIGITS_ONLY_PATTERN = /^\d+$/;
