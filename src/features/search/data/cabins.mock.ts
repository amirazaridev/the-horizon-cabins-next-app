const CREATED_AT = new Date("2025-04-01T10:00:00.000Z");

/**
 * شناسه‌ی شهرها در داده‌ی ماک فقط برای سازگاری با مدل دامنه است؛
 * تطبیق واقعی در repository بر اساس «نام شهر» انجام می‌شود.
 */
const MOCK_CITY_IDS = new Map<string, number>();

function cityId(name: string): number {
  const existing = MOCK_CITY_IDS.get(name);
  if (existing) return existing;
  const id = MOCK_CITY_IDS.size + 1;
  MOCK_CITY_IDS.set(name, id);
  return id;
}

export const MOCK_CABINS: Cabin[] = SEEDS.map((seed, index) => {
  const [
    name,
    cityName,
    maxCapacity,
    regularPrice,
    discount,
    bedrooms,
    bathrooms,
    areaSqm,
    amenities,
  ] = seed;

  return {
    id: 9001 + index,
    name,
    maxCapacity,
    regularPrice,
    discount,
    description: `اقامتگاه ${name} با ظرفیت ${maxCapacity} نفر در ${cityName}.`,
    amenities,
    bedrooms,
    bathrooms,
    areaSqm,
    images: [],
    latitude: null,
    longitude: null,
    rating: Math.round((4 + ((index * 7) % 10) / 10) * 10) / 10,
    city: { id: cityId(cityName), name: cityName },
    createdAt: CREATED_AT,
    updatedAt: CREATED_AT,
  };
});
